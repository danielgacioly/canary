#!/usr/bin/env python3
"""Generate the ship's observation table for the default mission plan.

    python data/generate_dataset.py

Writes (all deterministic, standard library only, no network):
  data/modelled/osd569_cbc.csv             blood counts moulded on the Inspiration4 pattern (origin simulated), from nasa_snapshot.json
  data/modelled/osd575_cmp.csv             creatinine, potassium, calcium and CRP moulded on the same pattern (origin simulated)
  backend/canary/data/observations.csv     one row per measurement, with its origin
  data/DATASET.md                          what is in the file, where it came from, how it would be collected
  data/missions/<package>/*.csv            the demo mission as spreadsheet packages (odyssey1-mars, -moon, -iss)

Real files in data/real/ (none ship with the demo) replace the simulated row with the same (crew_id, day, indicator).
"""
import csv
import datetime
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from canary.domain import assumptions as A  # noqa: E402
from canary.domain import catalog, goals, plan, registry, simdata  # noqa: E402

DEMO = simdata.load_demo_crew()  # the demo crew: seeds, records, story and PINs live here, never in the engine
DEMO_MISSION = DEMO["mission"]
DEMO_CREW = DEMO["crew"]
DEMO_RECORDS = DEMO["records"]
STORY = DEMO["story"]

MISSIONS_DIR = ROOT / "data" / "missions"
PACKAGES = [("odyssey1-mars", "mars"), ("odyssey1-moon", "moon"), ("odyssey1-iss", "iss")]
SIMULATED_TIME = "12:00"
HISTORY_START = -30  # first day of the mock goal history (pre-flight training)
MOCK_SOURCE = "mock: generated by data/generate_dataset.py"
LIST_SEP = ";"

# The storms of the demo, as data. The engine reads them from space_events.csv (storm flags, dose, the immune follow-up).
# They are simulated events that replay the pattern of two real records (the DONKI solar particle event of 10 May 2024 and the
# Curiosity RAD storm of 20 May 2024), placed in a fictional mission: origin simulated, never real, and the extra dose is a
# prototype figure.
SPACE_EVENTS = [
    ["replay-2024-05-10-sep", "sep", 152, 152, "transit;moon", 22, "simulated", "simulated",
     "simulated replay of the pattern of the NASA DONKI solar particle event of 10 May 2024"],
    ["replay-2024-05-20-rad", "mars", 222, 222, "mars", 2, "simulated", "simulated",
     "simulated replay of the pattern of the Curiosity RAD storm of 20 May 2024 at Gale crater"],
]
SPACE_EVENT_COLUMNS = ["id", "kind", "start_day", "end_day", "locations", "extra_dose_msv", "origin", "source", "note"]
OBS_PACKAGE_COLUMNS = simdata.COLUMNS + ["measured_at"]
GOAL_LOG_COLUMNS = ["crew_id", "day", "goal_id", "done", "done_at_time"]
SCENE_COLUMNS = ["index", "day", "location", "person", "storm", "when", "text"]
CREW_COLUMNS = ["id", "name", "role", "initials", "home"] + registry.RECORD_FIELDS + ["pin"]


def _write(path: pathlib.Path, header, rows) -> None:
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


def _launch_plus(days: int) -> str:
    return (datetime.date.fromisoformat(DEMO_MISSION["launch_date"]) + datetime.timedelta(days=days)).isoformat()


def package_legs(preset: str) -> list:
    return plan.preset_legs(preset, rover=True)


def mission_rows(preset: str) -> list:
    m = DEMO_MISSION
    name = m["name"] if preset == m["preset"] else plan.PRESETS[preset]["name"]
    return [[m["callsign"], name, m["launch_date"], preset, _launch_plus(STORY[0]["day"]), SIMULATED_TIME, MOCK_SOURCE]]


def crew_rows() -> list:
    rows = []
    for c in DEMO_CREW:
        rec = DEMO_RECORDS[c["id"]]
        row = [c["id"], c["name"], c["role"], c["initials"], c["home"]]
        for f in registry.RECORD_FIELDS:
            v = rec.get(f)
            row.append(LIST_SEP.join(v) if isinstance(v, list) else ("" if v is None else v))
        rows.append(row + [c["pin"]])
    return rows


def _cabin_rate(legs: list, day: int) -> float:
    """What the cabin dosimeter reads on one day: the rate of the place, plus the extra dose of a storm that starts that
    day and hits the place (so the measured series contains the storm and the engine adds nothing on top of it)."""
    loc = simdata.location_at(legs, day)
    rate = catalog.LOCATIONS[loc]["dose_rate"]
    extra = sum(e[5] for e in SPACE_EVENTS if e[2] == day and loc in e[4].split(LIST_SEP))
    return round(rate + extra, 4)


def package_observations(legs: list, rows: list) -> list:
    """The observation rows plus the cabin dosimeter, each with measured_at (launch date + day, 08:00 UTC)."""
    last = max(l["end"] for l in legs)
    quality = A.value("dose.quality_factor")  # mock only: the absorbed dose is the dose equivalent divided by it
    dose = [(simdata.CABIN, d, "dose_eq_rate", f"{_cabin_rate(legs, d):g}", "mSv/day", "simulated", "dosimeter", "mock:dosimeter",
             "dose equivalent") for d in range(0, last + 1)]
    dose += [(simdata.CABIN, d, "dose_rate", f"{_cabin_rate(legs, d) / quality:.4g}", "mGy/day", "simulated", "dosimeter", "mock:dosimeter",
              "absorbed dose") for d in range(0, last + 1)]
    allrows = sorted(list(rows) + dose, key=lambda r: (r[0], r[1], r[2]))
    return [list(r) + [f"{_launch_plus(r[1])}T08:00:00Z"] for r in allrows]


def goal_p(crew_id: str, goal_id: str, day: int) -> float:
    """goals._sim_done's probability for a day that is not today."""
    p = next(c["goal_p"] for c in DEMO_CREW if c["id"] == crew_id)
    g = catalog.PERSONAL_BY_ID.get(goal_id)
    if crew_id == "h" and 132 <= day <= 153 and g and g["area"] == "mental":
        p = 0.35
    if crew_id == "t" and 1 <= day <= 4:
        p = 0.3
    return p


def _clock(base_h: int, u: float) -> str:
    m = int(u * 240)  # 240 minutes: 08:00-11:59 or 18:00-21:59
    return f"{base_h + m // 60:02d}:{m % 60:02d}"


def goal_log_rows(legs: list) -> list:
    """One row per (crew, day, goal) the history would ever show as done (see goals._history / _sim_done).

    Done early (08:00-11:59) when h01 < 0.45*p, done late (18:00-21:59) when h01 < p. On the current mission day only
    the goals done by the simulated time count, which is exactly the old "p * 0.45"; past days count every row."""
    rows = []
    last = max(l["end"] for l in legs)
    for c in DEMO_CREW:
        cid = c["id"]
        for day in range(HISTORY_START, last + 1):
            for gid in goals.daily_goal_ids(simdata.location_at(legs, day)):
                p = goal_p(cid, gid, day)
                u = simdata.h01(f"goal:{cid}:{gid}:{day}")
                if u < p * 0.45:
                    rows.append([cid, day, gid, 1, _clock(8, simdata.h01(f"goaltime:{cid}:{gid}:{day}"))])
                elif u < p:
                    rows.append([cid, day, gid, 1, _clock(18, simdata.h01(f"goaltime:{cid}:{gid}:{day}"))])
    return rows


def scene_rows() -> list:
    return [[i, s["day"], s["loc"], s["me"], s["storm"] or "", s["when"], s["text"]] for i, s in enumerate(STORY)]


README = """# {callsign}: {name} (mission package)

A mission package is a folder of plain spreadsheets (UTF-8 CSV, header row, `,` separator) that opens in any
spreadsheet program. Canary reads a mission only from files like these. A real mission replaces this folder with
its own files of the same shape; nothing in the engine knows this demo.

Everything here is **mock** unless said otherwise. Generated by `data/generate_dataset.py`; do not edit by hand.

## Files

| File | What it holds |
| --- | --- |
| `mission.csv` | One row: callsign, name, launch date, plan preset, the simulated "today" (launch date at day {first_day}) and time of day, and where the data came from. |
| `legs.csv` | The itinerary: `start_day`, `end_day`, `location` and an optional `label` (the leg's name on screen). Day 0 is launch; negative days are pre-flight on Earth. |
| `crew.csv` | One row per person, one to six (the demo has four, `h`, `k`, `a` and `t`): `id`, name, role, initials, home, the personal record fields (lists such as `languages` are joined with `;`), `eva`, `prior_dose_msv` (empty means: estimate it from days in space) and the sign-in `pin`. |
| `observations.csv` | One row per measurement: `crew_id`, `day`, `indicator`, `value`, `unit`, `origin`, `method`, `source`, `note`, `measured_at` (launch date plus the day, 08:00 UTC). The cabin dosimeter appears as `crew_id` `cabin`, `indicator` `dose_eq_rate` (dose equivalent, mSv/day) and `dose_rate` (absorbed dose, mGy/day), one row each per day from day 0. A reading's context goes in the `note` as `[ctx activity=rest]` (pulse) or `[ctx position=seated]` (pressure). Bone density (`bone`, g/cm2) is a DXA scan: before launch and after landing only. |
| `space_events.csv` | Space-weather events: `id`, `kind`, `start_day`, `end_day`, `locations` (joined with `;`), `extra_dose_msv`, `origin`, `source`, `note`. |
| `goal_log.csv` | Which daily goals each person completed: `crew_id`, `day`, `goal_id`, `done` (always 1), `done_at_time`. A goal missing from the file was not done. On the current mission day only goals done at or before the simulated time of day count. |
| `scenes.csv` | The six steps of the guided demo story: `index`, `day`, `location`, `person`, `storm` (informational), `when`, `text`. |

## Real data and mock data

- **Nothing here is a real person's measurement.** Every row is `origin` = `simulated`. The blood counts (OSD-569,
  Inspiration4 complete blood count) and the creatinine, potassium, calcium and CRP values (OSD-575) are moulded on
  the Inspiration4 pattern: `origin` = `simulated`, `source` = `modelled on Inspiration4 (NASA OSDR OSD-569)` (or
  OSD-575). The storms in `space_events.csv` are simulated replays of the pattern of the DONKI event of 10 May 2024 and
  the Curiosity RAD storm of 20 May 2024: `origin` = `simulated`, with a prototype `extra_dose_msv`.
- **Mock:** the other indicators, the cabin dosimeter, the crew, the goal log and the scenes. The crew is fictional.

## Space events

Replays of storms. The immune "blood count due" warning covers the day a storm starts and the 13 days after it (the
rule `storm_follow_days`), for storms that hit the crew's place on their start day. A storm adds `extra_dose_msv` to the
dose of the day it starts, while the crew is in one of its `locations`. The cabin dosimeter rows of that day already
contain it (rate of the place plus `extra_dose_msv`), so the measured series holds the storm.
{plan_note}
## Public demo PINs

The PINs in `crew.csv` (1001 to 1004) are **public and for the demo only**. A real mission sets its own.
"""


def write_package(name: str, preset: str, recipes: dict, snapshot: dict, default_rows) -> pathlib.Path:
    out = MISSIONS_DIR / name
    out.mkdir(parents=True, exist_ok=True)
    legs = package_legs(preset)
    rows = default_rows if preset == plan.DEFAULT else simdata.Generator(legs, recipes, simdata.REAL_DIR, snapshot, DEMO_CREW).observations()
    _write(out / "mission.csv", ["callsign", "name", "launch_date", "preset", "simulated_today", "simulated_time", "source"],
           mission_rows(preset))
    _write(out / "legs.csv", ["start_day", "end_day", "location", "label"], [[l["start"], l["end"], l["location"], l["label"]] for l in legs])
    _write(out / "crew.csv", CREW_COLUMNS, crew_rows())
    _write(out / "observations.csv", OBS_PACKAGE_COLUMNS, package_observations(legs, rows))
    _write(out / "space_events.csv", SPACE_EVENT_COLUMNS, SPACE_EVENTS)
    _write(out / "goal_log.csv", GOAL_LOG_COLUMNS, goal_log_rows(legs))
    _write(out / "scenes.csv", SCENE_COLUMNS, scene_rows())
    note = "" if preset == plan.DEFAULT else (
        "\nThe storm replays belong to the Mars story (days 152 and 222). With this plan the crew is not in the places they "
        "name on those days, so they add nothing here.\n")
    (out / "README.md").write_text(README.format(callsign=DEMO_MISSION["callsign"], name=mission_rows(preset)[0][1],
                                                 first_day=STORY[0]["day"], plan_note=note), encoding="utf-8", newline="")
    return out


def main() -> None:
    recipes = simdata.load_recipes()
    snapshot = simdata.load_snapshot()
    simdata.MODELLED_DIR.mkdir(parents=True, exist_ok=True)
    simdata.write_csv(simdata.osd569_rows(snapshot, recipes, DEMO_CREW), simdata.MODELLED_DIR / "osd569_cbc.csv")
    simdata.write_csv(simdata.osd575_rows(snapshot, recipes, DEMO_CREW), simdata.MODELLED_DIR / "osd575_cmp.csv")

    legs = plan.PRESETS[plan.DEFAULT]["legs"]
    rows = simdata.Generator(legs, recipes, simdata.REAL_DIR, snapshot, DEMO_CREW).observations()
    simdata.write_csv(rows, simdata.OBS_FILE)
    text = simdata.report(rows, recipes, plan.PRESETS[plan.DEFAULT]["name"])
    simdata.REPORT_FILE.write_text(text, encoding="utf-8", newline="")

    for name, preset in PACKAGES:
        out = write_package(name, preset, recipes, snapshot, rows)
        print(f"Wrote {out.relative_to(ROOT)}/ ({(out / 'observations.csv').stat().st_size / 1e6:.2f} MB of observations)")

    size = simdata.OBS_FILE.stat().st_size
    print(text)
    print(f"Wrote {simdata.OBS_FILE.relative_to(ROOT)} ({len(rows):,} rows, {size / 1e6:.2f} MB), "
          f"{simdata.REPORT_FILE.relative_to(ROOT)}, data/modelled/osd569_cbc.csv and data/modelled/osd575_cmp.csv")


if __name__ == "__main__":
    main()
